# 交给分类器的历史预算：只需要认清“刚才在聊哪个产品”，不需要读完整篇回答，
# 所以按字符从尾部裁，助手回答的单条截断在节点侧完成。
MAX_INTENT_HISTORY_CHARS = 600


def build_intent_classify_prompt(query: str, history_text: str = "") -> str:
    """分类要把最近几轮一起交给模型。

    原实现刻意只给当前这一句，理由是“能走到兜底分类的输入不含实体信号，历史无从对齐”——
    这个前提被线上证伪了：**「本轮无实体信号」不等于「历史无可用实体」**。省略宾语的追问
    恰恰是本轮零信号、上一轮满信号，孤立判句就必然把业务追问当成“让助手自我介绍”。
    history_text 由调用方带角色前缀（用户/助手）拼好：话题实体常常只出现在助手回答里；
    分类结果只决定是否短路闲聊，不参与任何拒答判定，所以这里读助手文本不触碰 R2 红线。
    """
    context = str(history_text or "").strip()[-MAX_INTENT_HISTORY_CHARS:]
    if not context:
        return f"本轮输入：{query}"
    return (
        f"最近对话（已标注说话人，只用来判断本轮输入是否在追问其中提到的产品）：\n{context}\n\n"
        f"本轮输入：{query}"
    )
